package org.mozilla.javascript;

import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import org.mozilla.classfile.ByteCode;
import org.mozilla.classfile.ClassFileWriter;
import org.mozilla.javascript.autojs6.JavaSubclass;
import org.mozilla.javascript.lc.member.ExecutableBox;
import org.mozilla.javascript.lc.member.ExecutableOverload;
import org.mozilla.javascript.lc.member.NativeJavaField;

/**
 * AutoJs6 class syntax, fork only (ROADMAP D3 / D6): the package-private parts of the Java interop
 * that {@link org.mozilla.javascript.autojs6.JavaClassInheritance} uses for classes that extend a
 * Java class. It holds no logic of its own.
 *
 * <p>The methods are public for the {@code autojs6} package; they are not an API.
 */
public final class JavaInheritanceSupport {

    private JavaInheritanceSupport() {}

    /**
     * The adapter class of a superclass, interfaces and overridden method names, generated by
     * {@link JavaAdapter#createAdapterCode} once per signature in the cache of the scope that
     * {@code new JavaAdapter(...)} uses.
     */
    public static Class<?> adapterClass(
            VarScope scope,
            Class<?> superClass,
            Class<?>[] interfaces,
            Map<String, Integer> names) {
        JavaAdapter.JavaAdapterSignature sig = new JavaAdapter.JavaAdapterSignature();
        sig.superClass = superClass;
        sig.interfaces = interfaces;
        sig.names = names;
        // As JavaAdapter.getAdapterClass, which is private.
        ClassCache cache = ClassCache.get(scope);
        Map<JavaAdapter.JavaAdapterSignature, Class<?>> generated =
                cache.getInterfaceAdapterCacheMap();
        Class<?> adapterClass = generated.get(sig);
        if (adapterClass == null) {
            String adapterName = CLASS_ADAPTER_PREFIX + cache.newClassSerialNumber();
            byte[] code =
                    JavaAdapter.createAdapterCode(names, adapterName, superClass, interfaces, null);
            adapterClass = JavaAdapter.loadAdapterClass(adapterName, code);
            if (cache.isCachingEnabled()) {
                generated.put(sig, adapterClass);
            }
        }
        return adapterClass;
    }

    /** The methods of a class that an adapter class can override, as JavaAdapter finds them. */
    public static Method[] overridableMethods(Class<?> c) {
        return JavaAdapter.getOverridableMethods(c);
    }

    /** The index of the constructor that the Java overload resolution picks, or -1. */
    public static int findConstructor(Context cx, ExecutableBox[] ctors, Object[] args) {
        return NativeJavaMethod.findFunction(cx, ctors, args);
    }

    /** The argument types of a call as Java error messages show them. */
    public static String scriptSignature(Object[] args) {
        return NativeJavaMethod.scriptSignature(args);
    }

    /**
     * The string keys of the own data properties of an object whose values are functions, the
     * non-enumerable ones included; accessor properties are skipped without calling them.
     */
    public static List<String> ownFunctionNames(Scriptable obj) {
        List<String> names = new ArrayList<>();
        if (!(obj instanceof ScriptableObject)) {
            return names;
        }
        ScriptableObject so = (ScriptableObject) obj;
        for (Object id : so.getAllIds()) {
            if (!(id instanceof String)) {
                continue;
            }
            Slot<Scriptable> slot = so.getMap().query(id, 0);
            if (slot == null || slot instanceof AccessorSlot) {
                continue;
            }
            if (slot.getValue(so) instanceof Function) {
                names.add((String) id);
            }
        }
        return names;
    }

    /**
     * The value of an own data property of an object, without calling anything: {@link
     * Scriptable#NOT_FOUND} when there is no such property, {@link #ACCESSOR} for an accessor
     * property or an object that is not a {@link ScriptableObject}.
     */
    public static Object ownDataValue(Scriptable obj, String name) {
        if (!(obj instanceof ScriptableObject)) {
            return ACCESSOR;
        }
        ScriptableObject so = (ScriptableObject) obj;
        Slot<Scriptable> slot = so.getMap().query(name, 0);
        if (slot == null) {
            return Scriptable.NOT_FOUND;
        }
        if (slot instanceof AccessorSlot || slot instanceof LambdaSlot) {
            return ACCESSOR;
        }
        return slot.value;
    }

    /** See {@link #ownDataValue}. */
    public static final Object ACCESSOR = new Object();

    /**
     * The name of the adapter classes of classes that extend a Java class (and implement {@link
     * JavaSubclass}), which the generated code of JavaAdapter tells apart by it.
     */
    static final String CLASS_ADAPTER_PREFIX = "classadapter";

    private static boolean isClassAdapter(String adapterName) {
        return adapterName.startsWith(CLASS_ADAPTER_PREFIX);
    }

    /**
     * In a constructor of the adapter class of a class that extends a Java class, before the Java
     * constructor runs: stores the instance (the first parameter) as {@code delegee} and {@code
     * self} and the context factory (the second one), so that the methods the Java constructor
     * calls already reach the instance. The constructor stores them again afterwards.
     */
    static void storeEarly(ClassFileWriter cfw, String adapterName) {
        if (!isClassAdapter(adapterName)) {
            return;
        }
        cfw.add(ByteCode.ALOAD_0);
        cfw.add(ByteCode.ALOAD_1);
        cfw.add(ByteCode.PUTFIELD, adapterName, "delegee", "Lorg/mozilla/javascript/Scriptable;");
        cfw.add(ByteCode.ALOAD_0);
        cfw.add(ByteCode.ALOAD_1);
        cfw.add(ByteCode.PUTFIELD, adapterName, "self", "Lorg/mozilla/javascript/Scriptable;");
        cfw.add(ByteCode.ALOAD_0);
        cfw.add(ByteCode.ALOAD_2);
        cfw.add(
                ByteCode.PUTFIELD,
                adapterName,
                "factory",
                "Lorg/mozilla/javascript/ContextFactory;");
    }

    /**
     * At the start of a method of the adapter class of a class that extends a Java class: hands the
     * Java object to the instance ({@code delegee}) before calling its function, which matters for
     * the calls the Java constructor makes before the adapter constructor attaches it.
     */
    static void attachEarly(ClassFileWriter cfw, String adapterName) {
        if (!isClassAdapter(adapterName)) {
            return;
        }
        cfw.add(ByteCode.ALOAD_0);
        cfw.add(ByteCode.GETFIELD, adapterName, "delegee", "Lorg/mozilla/javascript/Scriptable;");
        cfw.add(ByteCode.ALOAD_0);
        cfw.addInvoke(
                ByteCode.INVOKESTATIC,
                "org/mozilla/javascript/autojs6/JavaClassInheritance",
                "attach",
                "(Lorg/mozilla/javascript/Scriptable;Ljava/lang/Object;)"
                        + "Lorg/mozilla/javascript/Scriptable;");
        cfw.add(ByteCode.POP);
    }

    /**
     * Whether a name of a wrapped Java object is a field that is not final or a bean property with
     * a setter: the members that an assignment changes on the Java object.
     */
    public static boolean isWritableJavaProperty(NativeJavaObject obj, String name) {
        Object member = obj.members.member(name);
        if (member instanceof ExecutableOverload.WithField) {
            member = ((ExecutableOverload.WithField) member).field;
        }
        if (member instanceof BeanProperty) {
            return ((BeanProperty) member).setter != null;
        }
        if (member instanceof NativeJavaField) {
            int mods = ((NativeJavaField) member).raw().getModifiers();
            return !Modifier.isFinal(mods) && !Modifier.isStatic(mods);
        }
        return false;
    }
}
